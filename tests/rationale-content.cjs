const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert'),path=require('node:path');
const base=path.join(__dirname,'..','public')+path.sep;
const context={window:{}};
vm.createContext(context);
vm.runInContext(fs.readFileSync(base+'story.js','utf8'),context);
const events={};
const root={innerHTML:'',querySelector(s){if(s==='[data-try-board]')return {addEventListener(n,fn){events[n]=fn}};return null}};
let role='', view='';
context.window.renderRationaleSection(root,{}, {setRole(v){role=v},navigate(v){view=v}});
for(const id of ['assumptions','persona','problem','why-this-stage','metrics'])assert(root.innerHTML.includes(`id="${id}"`) && root.innerHTML.includes(`href="#${id}"`));
assert.strictEqual((root.innerHTML.match(/<img src=/g)||[]).length,6);
assert.strictEqual((root.innerHTML.match(/<figure class="r-voice"/g)||[]).length,4);
assert(root.innerHTML.includes('A live AI model can be connected for Ask; automated extraction is proposed.'));
assert(!root.innerHTML.includes('Card 1 links here.')&&!root.innerHTML.includes('Lead:'));
assert(root.innerHTML.includes('The 13 conceptual journeys behind it (the working prototype includes eight sample cases)'));
assert(root.innerHTML.includes('class="r-top-pain"'));
for (const match of root.innerHTML.matchAll(/<img src="([^"]+)"/g)) assert(fs.existsSync(path.join(base, match[1])), `Missing image: ${match[1]}`);
vm.runInContext(fs.readFileSync(base+'architecture.js','utf8'),context);
const architecture={innerHTML:''};
context.window.renderArchitectureSection(architecture);
assert(architecture.innerHTML.includes('assets/architecture-overview.jpeg'));
assert(architecture.innerHTML.includes('Concept architecture'));
assert(fs.existsSync(path.join(base,'assets','architecture-overview.jpeg')));
events.click(); assert.strictEqual(role,'Priya Nair'); assert.strictEqual(view,'board');
console.log('PASS: five linked rationale sections, six diagrams, four simulated voices, assumptions disclosure, and Priya board CTA');
